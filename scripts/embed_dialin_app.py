#!/usr/bin/env python3
"""Embed the Dial-in web app (dialin-app/dialin/www) into the display firmware.

Writes src/display/plugins/dialin/app_bundle.h with every file as a byte array
plus a content hash. DialInPlugin copies the files to /dialin/www/ on the SD
card at start-up whenever the hash on the card differs, so no card reader is
needed. Run after changing the app:  python3 scripts/embed_dialin_app.py

Files are stored gzip-compressed as <name>.gz: ESPAsyncWebServer serves them with
Content-Encoding: gzip and an ETag from the gzip CRC, so browsers can cache them
and revalidate cheaply (and the content-based ETag changes with every new version).
"""
import gzip
import hashlib
import re
import os
import sys

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), ".."))
SRC = os.path.join(ROOT, "dialin-app", "dialin", "www")
OUT = os.path.join(ROOT, "src", "display", "plugins", "dialin", "app_bundle.h")


ASSET = re.compile(
    rb"""((?:from|import)\s*\(?\s*['"]|src=['"]|href=['"]|"src"\s*:\s*['"])((?:\./)?[\w./-]+\.(?:js|css|png|svg|webmanifest))(['"])"""
)


def add_version(rel, data, version):
    """Point every reference at <file>?v=<hash>.

    The URLs then change with each build, so the browser can keep the files for a
    long time instead of asking the machine about all of them on every visit.
    index.html itself is always re-checked, and it carries the new URLs.
    """
    if not rel.endswith((".html", ".js", ".webmanifest")):
        return data
    return ASSET.sub(lambda m: m.group(1) + m.group(2) + b"?v=" + version.encode() + m.group(3), data)


def main():
    files = []
    for dirpath, _, names in os.walk(SRC):
        for name in sorted(names):
            path = os.path.join(dirpath, name)
            rel = os.path.relpath(path, SRC).replace(os.sep, "/")
            with open(path, "rb") as f:
                files.append((rel, f.read()))
    files.sort()
    digest = hashlib.sha1()
    for rel, data in files:
        digest.update(rel.encode() + b"\0" + data)
    version = digest.hexdigest()[:12]

    lines = [
        "// Generated by scripts/embed_dialin_app.py from dialin-app/dialin/www. Do not edit.",
        "#pragma once",
        "#include <cstddef>",
        "#include <cstdint>",
        "",
        "namespace dialin_app {",
        f'static constexpr const char *VERSION = "{version}";',
        "struct File {",
        "    const char *path;",
        "    const uint8_t *data;",
        "    size_t size;",
        "};",
    ]
    files = [(rel, add_version(rel, data, version)) for rel, data in files]
    packed = [(rel + ".gz", gzip.compress(data, compresslevel=9, mtime=0)) for rel, data in files]
    for i, (rel, data) in enumerate(packed):
        body = ",".join(str(b) for b in data)
        lines.append(f"static const uint8_t FILE_{i}[] = {{{body}}};")
    lines.append("static const File FILES[] = {")
    for i, (rel, data) in enumerate(packed):
        lines.append(f'    {{"{rel}", FILE_{i}, {len(data)}}},')
    lines.append("};")
    lines.append(f"static constexpr size_t FILE_COUNT = {len(files)};")
    lines.append("} // namespace dialin_app")
    lines.append("")
    new = "\n".join(lines)
    old = open(OUT).read() if os.path.exists(OUT) else ""
    if new != old:
        with open(OUT, "w") as f:
            f.write(new)
    total = sum(len(d) for _, d in files)
    packed_total = sum(len(d) for _, d in packed)
    print(f"embed_dialin_app: {len(files)} files, {total} bytes ({packed_total} gzipped), version {version}")
    if "--check" in sys.argv and new != old:
        print("app_bundle.h was out of date (regenerated)")
        sys.exit(1)


main()
